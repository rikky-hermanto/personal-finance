-- PF-S08 expand stage. Safe to apply before owner mapping; no existing row is claimed.
-- Do not apply the later enforce stage until the preflight and explicit mapping pass.

ALTER TABLE public.transactions ADD COLUMN user_id uuid;
ALTER TABLE public.uploaded_files ADD COLUMN user_id uuid;
ALTER TABLE public.category_rules ADD COLUMN user_id uuid;
ALTER TABLE public.wallet_account_aliases ADD COLUMN user_id uuid;

CREATE INDEX idx_transactions_owner_date_id ON public.transactions (user_id, date, id);
CREATE INDEX idx_uploaded_files_owner_hash ON public.uploaded_files (user_id, file_hash);
CREATE INDEX idx_category_rules_owner ON public.category_rules (user_id);
CREATE INDEX idx_wallet_aliases_owner_text ON public.wallet_account_aliases (user_id, lower(btrim(alias_text)));

-- A receipt will make synchronous submit retries idempotent after the checked
-- mutation function is installed. No client can use this table during expand.
CREATE TABLE public.cashflow_import_receipts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES auth.users(id),
    request_id uuid NOT NULL,
    payload_digest text NOT NULL,
    file_hash text,
    committed_result jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT cashflow_import_receipts_owner_request UNIQUE (user_id, request_id)
);
CREATE UNIQUE INDEX cashflow_import_receipts_owner_file
    ON public.cashflow_import_receipts (user_id, file_hash)
    WHERE file_hash IS NOT NULL;
ALTER TABLE public.cashflow_import_receipts ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.cashflow_import_receipts FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.cashflow_import_receipts_id_seq FROM PUBLIC, anon, authenticated;

-- Quarantine direct PostgREST/GraphQL access during mapping. The old permissive
-- policies still exist in expand, so grants must be removed before pilot users
-- receive tokens. Service-role/admin access is unchanged for the controlled backfill.
REVOKE ALL ON ALL TABLES IN SCHEMA public FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.category_presets TO authenticated;
